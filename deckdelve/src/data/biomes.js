export const BIOME_BY_ID = Object.fromEntries(BIOMES.map((b) => [b.id, b]));

export function getBiome(id) {
  const b = BIOME_BY_ID[id];
  if (!b) throw new Error(`unknown biome: ${id}`);
  return b;
}
